#!/usr/bin/env python3
"""Render public Go2 reference motions with cameras fixed to the world frame."""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import re
import subprocess
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[2]


def quat_yaw_xyzw(q):
    x, y, z, w = q
    return math.atan2(2.0 * (w * z + x * y), 1.0 - 2.0 * (y * y + z * z))


def load_pipeline_ranges(path):
    ranges = {}
    for line in path.read_text().splitlines():
        match = re.match(r'^"([^ ]+) ([^ ]+) (\d+) (-?\d+)"$', line.strip())
        if match:
            name, source_file, first, last = match.groups()
            ranges[name] = (source_file, int(first), int(last))
    return ranges


def load_kine2go(data_dir, raw_dir, range_file):
    manifest = json.loads((data_dir / "manifest.json").read_text())
    ranges = load_pipeline_ranges(range_file)
    motions = []
    for name in manifest["clips"]:
        if name not in ranges:
            raise ValueError(f"No pinned pipeline frame range for {name}")
        rows = np.loadtxt(data_dir / f"{name}.csv", delimiter=",", ndmin=2)
        source_file, first, last = ranges[name]
        stop = len(rows) if last < 0 else last + 1
        if rows.shape[1] != 19 or not np.isfinite(rows).all() or stop > len(rows):
            raise ValueError(f"Malformed Kine2Go reference {name}: {rows.shape}")
        rows = rows[first:stop]
        meta = json.loads((raw_dir / "data" / name / "clip.json").read_text())
        motions.append({
            "name": name,
            "source": "Kine2Go Go2-retargeted reference",
            "description": meta.get("description", ""),
            "license": meta.get("license", "see clip metadata"),
            "source_file": source_file,
            "source_range_inclusive": [first, None if last < 0 else last],
            "fps": float(manifest["source_fps"]),
            "rows": rows,
        })
    return motions


def load_optimized_go2(data_dir):
    motions = []
    if not data_dir.exists():
        return motions
    for path in sorted(data_dir.glob("*_50hz.txt")):
        payload = json.loads(path.read_text())
        rows = np.asarray(payload["Frames"], dtype=np.float64)
        if rows.ndim != 2 or rows.shape[1] < 19 or not np.isfinite(rows[:, :19]).all():
            raise ValueError(f"Malformed Go2 trajectory file: {path}")
        motions.append({
            "name": path.stem,
            "source": "SE(3) whole-body trajectory optimization reference",
            "description": "Generated by the public go2_flip_TO optimizer; not a measured Go2 demonstration.",
            "license": "BSD-2-Clause source repository; see third_party/go2_flip_TO/LICENSE",
            "source_file": str(path.relative_to(ROOT)),
            "source_range_inclusive": [0, len(rows) - 1],
            "fps": 1.0 / float(payload["FrameDuration"]),
            "rows": rows[:, :19],
        })
    return motions


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kine2go-dir", type=Path, default=ROOT / "amp_supermimic/data/go2/kine2go_all40")
    parser.add_argument("--kine2go-raw-dir", type=Path, default=ROOT / "amp_supermimic/data/raw/kine2go_all40")
    parser.add_argument("--range-file", type=Path, default=ROOT / "amp_supermimic/data/raw/kine2go_inward_review/PIPELINE_motion_ranges.txt")
    parser.add_argument("--optimized-dir", type=Path, default=ROOT / "third_party/go2_flip_TO/datasets/go2/mocap_motions_go2")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "amp_supermimic/outputs/go2_motion_catalog")
    parser.add_argument("--video-fps", type=int, default=24)
    parser.add_argument("--width", type=int, default=640)
    parser.add_argument("--height", type=int, default=360)
    args = parser.parse_args()

    sys.path.insert(0, str(ROOT / "third_party/trackerlab_supermimic/scripts/rls/supermimic"))
    from bootstrap import configure_paths
    configure_paths()
    from trackerTask.supermimic.robots import get_robot
    import mujoco

    motions = load_kine2go(args.kine2go_dir, args.kine2go_raw_dir, args.range_file)
    motions += load_optimized_go2(args.optimized_dir)
    if not motions:
        raise ValueError("No Go2 motion references were found")

    spec = get_robot("go2")
    model = mujoco.MjModel.from_xml_path(str(Path(spec.mjcf_path).resolve()))
    model.vis.global_.offwidth = max(int(model.vis.global_.offwidth), args.width)
    model.vis.global_.offheight = max(int(model.vis.global_.offheight), args.height)
    data = mujoco.MjData(model)
    joint_ids = np.array([model.joint(name).id for name in spec.joint_names])
    joint_qpos = model.jnt_qposadr[joint_ids]

    main_renderer = mujoco.Renderer(model, height=args.height, width=args.width)
    side_renderer = mujoco.Renderer(model, height=args.height, width=args.width)
    main_camera = mujoco.MjvCamera()
    side_camera = mujoco.MjvCamera()
    for camera in (main_camera, side_camera):
        camera.type = mujoco.mjtCamera.mjCAMERA_FREE
        camera.elevation = -12
    main_camera.distance, main_camera.azimuth = 1.65, 135.0
    side_camera.distance, side_camera.azimuth = 1.35, 0.0

    args.output_dir.mkdir(parents=True, exist_ok=True)
    video_path = args.output_dir / "go2_public_motion_catalog.mp4"
    metrics_path = args.output_dir / "go2_public_motion_catalog.json"

    segments = []
    rendered_counts = []
    cursor = 0
    for index, motion in enumerate(motions, 1):
        rows = motion["rows"]
        duration = (len(rows) - 1) / motion["fps"]
        n_frames = max(2, round(duration * args.video_fps) + 1)
        repeats = min(3, max(1, math.ceil(1.25 / max(duration, 1e-6)))) if motion["source"].startswith("Kine2Go") else 1
        count = n_frames * repeats
        segments.append({
            "name": motion["name"],
            "source": motion["source"],
            "description": motion["description"],
            "source_file": motion["source_file"],
            "source_range_inclusive": motion["source_range_inclusive"],
            "license": motion["license"],
            "source_fps": motion["fps"],
            "source_frames": int(len(rows)),
            "source_duration_seconds": round(duration, 3),
            "preview_repeats": repeats,
            "start_frame": cursor,
            "motion_end_frame": cursor + count,
            "root_xy_displacement_m": (rows[-1, :2] - rows[0, :2]).tolist(),
            "net_yaw_deg": round(math.degrees(np.unwrap([quat_yaw_xyzw(q) for q in rows[:, 3:7]])[-1] -
                                                   np.unwrap([quat_yaw_xyzw(q) for q in rows[:, 3:7]])[0]), 2),
        })
        cursor += count + max(1, args.video_fps // 3)
        rendered_counts.append((n_frames, repeats))

    draw_filters = [
        "drawbox=x=0:y=0:w=iw:h=62:color=black@0.75:t=fill",
        "drawtext=fontfile=/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf:"
        "text='Go2 public motion references | fixed world azimuth cameras':"
        "x=16:y=5:fontsize=18:fontcolor=white",
    ]
    for index, segment in enumerate(segments, 1):
        start = segment["start_frame"] / args.video_fps
        end = max(start, (segment["motion_end_frame"] - 1) / args.video_fps)
        title = f"{index:02d}/{len(segments):02d} {segment['name']}"
        draw_filters.append(
            "drawtext=fontfile=/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf:"
            f"text='{title}':x=16:y=32:fontsize=19:fontcolor=0xFFD166:"
            f"enable='between(t,{start:.3f},{end:.3f})'"
        )
    ffmpeg = subprocess.Popen([
        "ffmpeg", "-y", "-loglevel", "error",
        "-f", "rawvideo", "-pixel_format", "rgb24",
        "-video_size", f"{args.width * 2}x{args.height}",
        "-framerate", str(args.video_fps), "-i", "-",
        "-vf", ",".join(draw_filters),
        "-an", "-c:v", "libx264", "-preset", "veryfast",
        "-crf", "21", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
        str(video_path),
    ], stdin=subprocess.PIPE)

    metrics = {
        "video": str(video_path),
        "video_fps": args.video_fps,
        "camera": "Both azimuths are fixed in world coordinates; lookat follows root translation.",
        "playback_note": "Kinematic reference playback only; not PD or physical replay.",
        "clips": segments,
    }

    try:
        for motion, (n_frames, repeats) in zip(motions, rendered_counts):
            rows = motion["rows"]
            sample = np.rint(np.linspace(0, len(rows) - 1, n_frames)).astype(int)
            last_image = None
            for _ in range(repeats):
                for frame_index in sample:
                    row = rows[frame_index]
                    data.qpos[:3] = row[:3]
                    data.qpos[3:7] = row[[6, 3, 4, 5]]
                    data.qpos[joint_qpos] = row[7:19]
                    mujoco.mj_forward(model, data)
                    target = row[:3].copy()
                    target[2] += 0.08
                    main_camera.lookat[:] = target
                    side_camera.lookat[:] = target
                    main_renderer.update_scene(data, camera=main_camera)
                    side_renderer.update_scene(data, camera=side_camera)
                    frame = np.concatenate((main_renderer.render(), side_renderer.render()), axis=1)
                    ffmpeg.stdin.write(frame.tobytes())
                    last_image = frame
            for _ in range(max(1, args.video_fps // 3)):
                ffmpeg.stdin.write(last_image.tobytes())
    finally:
        main_renderer.close()
        side_renderer.close()
        if ffmpeg.stdin:
            ffmpeg.stdin.close()
    if ffmpeg.wait() != 0:
        raise RuntimeError("ffmpeg failed to encode motion catalog")
    metrics_path.write_text(json.dumps(metrics, indent=2) + "\n")
    print(json.dumps({
        "video": str(video_path),
        "metrics": str(metrics_path),
        "motions": len(motions),
        "duration_seconds": round(cursor / args.video_fps, 2),
    }, indent=2))


if __name__ == "__main__":
    main()
